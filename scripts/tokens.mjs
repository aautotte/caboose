// Writes the design tokens (design/tokens.json and tokens.light.json) as CSS for the app:
//   src/renderer/src/styles/tokens.css          --gc-* custom properties, dark by default, light and "system" themes
//   src/renderer/src/styles/tailwind.theme.css  Tailwind's theme mapped onto them (bg-surface, text-muted, ...)
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const load = (name) => JSON.parse(readFileSync(join(root, 'design', name), 'utf8'))
const out = join(root, 'src', 'renderer', 'src', 'styles')

const indent = (lines, pad) => lines.map((l) => pad + l).join('\n')

function themed(t, pad) {
  const lines = [`color-scheme: ${t.theme};`]
  for (const [k, v] of Object.entries(t.color)) lines.push(`--gc-color-${k}: ${v};`)
  for (const [k, v] of Object.entries(t.shadow)) lines.push(`--gc-shadow-${k}: ${v};`)
  return indent(lines, pad)
}

function fixed(t) {
  const lines = [`--gc-font-sans: ${t.font.sans};`, `--gc-font-mono: ${t.font.mono};`]
  for (const [k, v] of Object.entries(t.type)) {
    lines.push(`--gc-text-${k}: ${v.size}px;`, `--gc-text-${k}--line-height: ${v.line}px;`, `--gc-text-${k}--font-weight: ${v.weight};`)
  }
  t.space.forEach((v, i) => lines.push(`--gc-space-${i}: ${v}px;`))
  for (const [k, v] of Object.entries(t.radius)) lines.push(`--gc-radius-${k}: ${v}px;`)
  for (const [k, v] of Object.entries(t.motion)) lines.push(`--gc-motion-${k}: ${v};`)
  for (const [k, v] of Object.entries(t.layout)) lines.push(`--gc-${k}: ${v}px;`)
  for (const [k, v] of Object.entries(t.z)) lines.push(`--gc-z-${k}: ${v};`)
  return indent(lines, '  ')
}

const tokensCss = (dark, light) => `/* GENERATED by scripts/tokens.mjs from design/tokens.json + tokens.light.json. Do not edit by hand. */

:root {
${fixed(dark)}
}

/* dark is the default */
:root,
:root[data-theme="dark"] {
${themed(dark, '  ')}
}

:root[data-theme="light"] {
${themed(light, '  ')}
}

@media (prefers-color-scheme: light) {
  :root[data-theme="system"] {
${themed(light, '    ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root { --gc-motion-fast: 0ms; --gc-motion-base: 0ms; }
}

html, body {
  background: var(--gc-color-bg);
  color: var(--gc-color-text);
  font-family: var(--gc-font-sans);
  font-size: var(--gc-text-base);
  line-height: var(--gc-text-base--line-height);
}
`

function tailwindCss(dark) {
  const lines = ['--color-*: initial;']
  for (const k of Object.keys(dark.color)) lines.push(`--color-${k}: var(--gc-color-${k});`)
  lines.push('--font-sans: var(--gc-font-sans);', '--font-mono: var(--gc-font-mono);')
  for (const k of Object.keys(dark.type)) {
    lines.push(`--text-${k}: var(--gc-text-${k});`, `--text-${k}--line-height: var(--gc-text-${k}--line-height);`, `--text-${k}--font-weight: var(--gc-text-${k}--font-weight);`)
  }
  lines.push('--spacing: 4px;')
  for (const k of Object.keys(dark.radius)) lines.push(`--radius-${k}: var(--gc-radius-${k});`)
  for (const k of Object.keys(dark.shadow)) lines.push(`--shadow-${k}: var(--gc-shadow-${k});`)
  lines.push(`--ease-out: ${dark.motion.ease};`)
  return `/* GENERATED by scripts/tokens.mjs. In the app's main stylesheet:
     @import "tailwindcss";
     @import "./tokens.css";
     @import "./tailwind.theme.css";
   Colours by role: bg-surface, border-border, text-danger, bg-diff-add-bg, stroke-lane-3 ... */

@theme inline {
${indent(lines, '  ')}
}

/* Short aliases so markup reads text-muted / border-input instead of text-text-muted. */
@utility text-muted { color: var(--gc-color-text-muted); }
@utility text-disabled { color: var(--gc-color-text-disabled); }
@utility border-input { border-color: var(--gc-color-border-input); }
@utility ring-focus { outline: 2px solid var(--gc-color-focus-ring); outline-offset: 1px; }
`
}

const dark = load('tokens.json')
const light = load('tokens.light.json')
const a = Object.keys(dark.color)
const b = Object.keys(light.color)
const diff = [...a.filter((k) => !b.includes(k)), ...b.filter((k) => !a.includes(k))]
if (diff.length) {
  console.error(`Role names differ between tokens.json and tokens.light.json: ${diff.join(', ')}`)
  process.exit(1)
}
for (const [name, text] of [
  ['tokens.css', tokensCss(dark, light)],
  ['tailwind.theme.css', tailwindCss(dark)]
]) {
  writeFileSync(join(out, name), text)
  console.log('wrote', join(out, name))
}
